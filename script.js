const menuButton = document.querySelector(".menu-button");
const navLinks = document.querySelector(".nav-links");
if (menuButton && navLinks) {
  const setOpen = (open) => {
    navLinks.classList.toggle("open", open);
    menuButton.setAttribute("aria-expanded", String(open));
    menuButton.setAttribute("aria-label", open ? "Close navigation" : "Open navigation");
  };
  menuButton.addEventListener("click", () => setOpen(!navLinks.classList.contains("open")));
  navLinks.querySelectorAll("a").forEach((link) => link.addEventListener("click", () => setOpen(false)));
}

const hasToggle = document.querySelector("[data-language-toggle]");

function applyLanguage(language) {
  const copy = translations[language] || translations.en;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = copy[node.getAttribute("data-i18n")];
    if (value) node.textContent = value;
  });
  document.querySelectorAll("[data-language-toggle]").forEach((button) => {
    button.textContent = language === "hi" ? "English" : "हिंदी";
    button.setAttribute("aria-label", language === "hi" ? "Switch language to English" : "भाषा हिंदी में बदलें");
  });
  try { localStorage.setItem("seemara.language", language); } catch (e) {}
}

// Pages without a toggle (blog, about) stay in English.
if (hasToggle) {
  let saved = "en";
  try { saved = localStorage.getItem("seemara.language") || "en"; } catch (e) {}
  if (saved !== "en") applyLanguage(saved);
  document.querySelectorAll("[data-language-toggle]").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(document.documentElement.lang === "hi" ? "en" : "hi"));
  });
}

document.querySelectorAll("[data-year]").forEach((node) => { node.textContent = String(new Date().getFullYear()); });

const revealItems = document.querySelectorAll(".reveal");
document.documentElement.classList.add("js-reveal");
if ("IntersectionObserver" in window && !matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) { entry.target.classList.add("visible"); observer.unobserve(entry.target); }
    });
  }, { threshold: 0.12, rootMargin: "0px 0px -40px 0px" });
  revealItems.forEach((el) => observer.observe(el));
} else {
  revealItems.forEach((el) => el.classList.add("visible"));
}
